pub struct Civil {
    pub year: i32,
    pub month: u8,
    pub day: u8,
    pub hour: u8,
    pub minute: u8,
    pub second: u8,
    pub dow: u8,
}

pub fn civil_of(unix_ms: i64, off_min: i32) -> Civil {
    let local = unix_ms + (off_min as i64) * MS_MIN;
    let days = local.div_euclid(MS_DAY);
    let rem = local.rem_euclid(MS_DAY);
    let (y, m, d) = civil_from_days(days);
    Civil {
        year: y,
        month: m,
        day: d,
        hour: (rem / MS_HOUR) as u8,
        minute: ((rem % MS_HOUR) / MS_MIN) as u8,
        second: ((rem % MS_MIN) / 1000) as u8,
        dow: dow_from_days(days),
    }
}

fn nth_weekday_of_month(year: i32, month: u8, week: i8, weekday: u8) -> i64 {
    let first = days_from_civil(i64::from(year), u32::from(month), 1);
    let first_dow = dow_from_days(first);
    let mut delta = (weekday as i64 + 7 - first_dow as i64) % 7;
    if week >= 1 {
        delta += (week as i64 - 1) * 7;
        let dim = days_in_month(year, month) as i64;
        let day = 1 + delta;
        if day > dim {
            delta -= 7;
        }
    } else {
        let dim = days_in_month(year, month) as i64;
        let last_dow = (first_dow + dim as u8 - 1) % 7;
        let back = (last_dow as i64 + 7 - weekday as i64) % 7;
        delta = dim - 1 - back - ((-week as i64 - 1) * 7);
    }
    first + delta
}

fn transition_ms_utc(year: i32, t: TzTransition, frame_off_min: i32) -> i64 {
    let days = nth_weekday_of_month(year, t.month, t.week, t.weekday);
    let wall_ms = days * MS_DAY + (t.hour as i64) * MS_HOUR;
    wall_ms - (frame_off_min as i64) * MS_MIN
}

#[inline]
fn emb_offset(emb: &EmbTable, unix_ms: i64) -> i32 {
    let sec = unix_ms.div_euclid(MS_SEC);
    let i = match emb.ts.binary_search(&sec) {
        Ok(i) => i,
        Err(0) => 0,
        Err(i) => i - 1,
    };
    i32::from(emb.off[i])
}

#[derive(Clone, Copy)]
struct RuleCache {
    zone: u16,
    year: i32,
    on: i64,
    off: i64,
    dst: i32,
}

thread_local! {
    static RULE_CACHE: std::cell::Cell<RuleCache> = std::cell::Cell::new(RuleCache {
        zone: u16::MAX,
        year: 0,
        on: 0,
        off: 0,
        dst: 0,
    });
}
pub fn tz_offset_min(zone: TzIdx, unix_ms: i64) -> i32 {
    let c = core_of(zone);
    if c.emb != 0 {
        let t = EMB_TABLES[c.emb as usize];
        let sec = unix_ms.div_euclid(MS_SEC);
        if t.ts.is_empty() || sec < t.ts[0] {
            return i32::from(c.pre);
        }
        return emb_offset(t, unix_ms);
    }
    if c.rule == RULE_NONE {
        return i32::from(c.std_min);
    }
    let year = year_from_days(unix_ms.div_euclid(MS_DAY));
    let std_min = i32::from(c.std_min);
    let rv = RULE_CACHE.with(|rc| {
        let b = rc.get();
        if b.zone == zone && b.year == year {
            b
        } else {
            let rule = &RULES[c.rule as usize];
            let nb = RuleCache {
                zone,
                year,
                on: transition_ms_utc(year, rule.start, std_min),
                off: transition_ms_utc(year, rule.end, std_min + rule.dst_add_min),
                dst: std_min + rule.dst_add_min,
            };
            rc.set(nb);
            nb
        }
    });
    let in_dst = if rv.on <= rv.off {
        unix_ms >= rv.on && unix_ms < rv.off
    } else {
        unix_ms >= rv.on || unix_ms < rv.off
    };
    if in_dst {
        rv.dst
    } else {
        std_min
    }
}
pub fn tz_offset_for(name: &str, unix_ms: i64) -> i32 {
    tz_offset_zone(zone_of(name), unix_ms)
}

