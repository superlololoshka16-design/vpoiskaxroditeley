fn abbr_is_offset_form(abbr: &str) -> bool {
    let b = abbr.as_bytes();
    (b.first().is_some_and(|c| *c == b'+' || *c == b'-') && b.len() >= 2)
        || b.is_empty()
        || b == b"GMT"
        || b == b"UT"
}

fn push_offset_into(out: &mut compact_str::CompactString, off_min: i32, colon: bool) {
    let sign = if off_min < 0 { '-' } else { '+' };
    let a = off_min.unsigned_abs();
    let h = (a / 60) as i64;
    let m = (a % 60) as i64;
    out.push(sign);
    if colon {
        crate::math::push_int_into(out, h);
        if m != 0 {
            out.push(':');
            crate::math::push_int_padded_into(out, m, 2);
        }
    } else {
        crate::math::push_int_padded_into(out, h, 2);
        crate::math::push_int_padded_into(out, m, 2);
    }
}

#[inline]
pub fn tz_offset_zone(zone: Option<TzIdx>, unix_ms: i64) -> i32 {
    zone.map(|z| tz_offset_min(z, unix_ms)).unwrap_or(0)
}

pub fn zone_label_zone(
    zone: Option<TzIdx>,
    unix_ms: i64,
    long: bool,
    out: &mut compact_str::CompactString,
) {
    let Some(zone) = zone else {
        out.push_str("UTC");
        return;
    };
    let off = tz_offset_min(zone, unix_ms);
    let dst = off != i32::from(core_of(zone).std_min);
    if long {
        push_long_name(out, zone, dst, off);
    } else {
        push_abbrev(out, zone, dst, off);
    }
}

fn push_abbrev(out: &mut compact_str::CompactString, zone: TzIdx, dst: bool, off_min: i32) {
    let d = ZDISPLAY[zone as usize];
    let abbr = if dst { d.abbr_dst } else { d.abbr_std };
    if abbr_is_offset_form(abbr) {
        push_offset_into(out, off_min, true);
    } else {
        out.push_str(abbr);
    }
}

